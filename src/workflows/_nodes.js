// ---------------------------------------------------------------------------
// _nodes.js — small factories that produce n8n node JSON.
// Node versions are pinned to ones available on n8n >= 1.80 (Cloud and
// recent self-hosted), and checked by `npm run validate:n8n`.
// ---------------------------------------------------------------------------
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const LIB_DIR = path.join(__dirname, '..', 'lib');

/** Deterministic UUID so rebuilding a client produces stable node/webhook IDs. */
function stableId(...parts) {
  const h = crypto.createHash('sha1').update(parts.join('|')).digest('hex');
  return [h.slice(0, 8), h.slice(8, 12), '4' + h.slice(13, 16), '8' + h.slice(17, 20), h.slice(20, 32)].join('-');
}

/** Read lib modules and strip the Node-only require/export blocks. */
function lib(names) {
  return names
    .map((n) => fs.readFileSync(path.join(LIB_DIR, n + '.js'), 'utf8')
      .replace(/\/\* n8n:strip-start \*\/[\s\S]*?\/\* n8n:strip-end \*\/\n?/g, '')
      .trim())
    .join('\n\n');
}

/**
 * Compose a Code node's JavaScript: library + client config + glue code.
 * The config is frozen in at build time — change client.config.json and rebuild.
 */
function composeCode(ctx, libs, glue) {
  return [
    '// ===== Generated by clinic-automation-kit (scripts/build.js) — client: ' + ctx.config.client.slug + ' =====',
    '// Edit src/ + clients/<slug>/client.config.json and rebuild instead of editing here.',
    '',
    lib(libs),
    '',
    '// ----- client config (from client.config.json) -----',
    'const CONFIG = ' + JSON.stringify(ctx.runtimeConfig, null, 2) + ';',
    '',
    '// ----- workflow logic -----',
    glue.trim(),
    '',
  ].join('\n');
}

function base(ctx, name, type, typeVersion, position, parameters, extra) {
  return Object.assign({
    parameters,
    id: stableId(ctx.config.client.slug, ctx.workflowKey, name),
    name,
    type,
    typeVersion,
    position,
  }, extra || {});
}

function credential(ctx, key, type) {
  const c = (ctx.config.n8n && ctx.config.n8n.credentials && ctx.config.n8n.credentials[key]) || {};
  return { [type]: { id: c.id || '', name: c.name || ctx.defaultCredentialNames[key] } };
}

const N = {
  /** Any node not covered by a dedicated factory. */
  node(ctx, name, type, typeVersion, position, parameters, extra) {
    return base(ctx, name, type, typeVersion, position, parameters, extra);
  },

  code(ctx, name, position, libs, glue, extra) {
    return base(ctx, name, 'n8n-nodes-base.code', 2, position, { jsCode: composeCode(ctx, libs, glue) }, extra);
  },

  formTrigger(ctx, name, position, { title, description, path: formPath, fields, buttonLabel }) {
    return base(ctx, name, 'n8n-nodes-base.formTrigger', 2.2, position, {
      formTitle: title,
      formDescription: description,
      formFields: { values: fields },
      options: { path: formPath, buttonLabel: buttonLabel || 'Submit', appendAttribution: false },
    }, { webhookId: stableId(ctx.config.client.slug, ctx.workflowKey, name, 'webhook') });
  },

  formEnding(ctx, name, position, title, message) {
    return base(ctx, name, 'n8n-nodes-base.form', 1, position, {
      operation: 'completion',
      completionTitle: title,
      completionMessage: message,
      options: {},
    }, { webhookId: stableId(ctx.config.client.slug, ctx.workflowKey, name, 'webhook') });
  },

  sheetsReadAll(ctx, name, position) {
    return base(ctx, name, 'n8n-nodes-base.googleSheets', 4.5, position, {
      operation: 'read',
      documentId: { __rl: true, value: ctx.config.google.sheet_id, mode: 'id' },
      sheetName: { __rl: true, value: ctx.config.google.appointments_tab, mode: 'name' },
      options: {},
    }, {
      alwaysOutputData: true, // first booking of a new sheet = 0 rows; don't stop the workflow
      credentials: credential(ctx, 'google_sheets', 'googleSheetsOAuth2Api'),
    });
  },

  sheetsAppend(ctx, name, position) {
    return base(ctx, name, 'n8n-nodes-base.googleSheets', 4.5, position, {
      operation: 'append',
      documentId: { __rl: true, value: ctx.config.google.sheet_id, mode: 'id' },
      sheetName: { __rl: true, value: ctx.config.google.appointments_tab, mode: 'name' },
      columns: { mappingMode: 'autoMapInputData', value: {}, matchingColumns: [], schema: [] },
      options: { cellFormat: 'RAW' }, // keep "2026-11-18" / "17:30" as plain text
    }, { credentials: credential(ctx, 'google_sheets', 'googleSheetsOAuth2Api') });
  },

  sheetsUpdate(ctx, name, position) {
    return base(ctx, name, 'n8n-nodes-base.googleSheets', 4.5, position, {
      operation: 'update',
      documentId: { __rl: true, value: ctx.config.google.sheet_id, mode: 'id' },
      sheetName: { __rl: true, value: ctx.config.google.appointments_tab, mode: 'name' },
      columns: { mappingMode: 'autoMapInputData', value: {}, matchingColumns: ['appointment_id'], schema: [] },
      options: { cellFormat: 'RAW' },
    }, { credentials: credential(ctx, 'google_sheets', 'googleSheetsOAuth2Api') });
  },

  schedule(ctx, name, position, cron) {
    return base(ctx, name, 'n8n-nodes-base.scheduleTrigger', 1.2, position, {
      rule: { interval: [{ field: 'cronExpression', expression: cron }] },
    });
  },

  /** IF node on a boolean expression: true -> output 0, false -> output 1 */
  ifTrue(ctx, name, position, expression) {
    return base(ctx, name, 'n8n-nodes-base.if', 2.2, position, {
      conditions: {
        options: { caseSensitive: true, leftValue: '', typeValidation: 'loose', version: 2 },
        conditions: [{
          id: stableId(ctx.config.client.slug, ctx.workflowKey, name, 'cond'),
          leftValue: expression,
          rightValue: '',
          operator: { type: 'boolean', operation: 'true', singleValue: true },
        }],
        combinator: 'and',
      },
      looseTypeValidation: true,
      options: {},
    });
  },

  /** Switch on a string expression, one output per value (in order). */
  switchOn(ctx, name, position, expression, values) {
    return base(ctx, name, 'n8n-nodes-base.switch', 3.2, position, {
      rules: {
        values: values.map((v) => ({
          conditions: {
            options: { caseSensitive: true, leftValue: '', typeValidation: 'strict', version: 2 },
            conditions: [{
              id: stableId(ctx.config.client.slug, ctx.workflowKey, name, v),
              leftValue: expression,
              rightValue: v,
              operator: { type: 'string', operation: 'equals' },
            }],
            combinator: 'and',
          },
          renameOutput: true,
          outputKey: v,
        })),
      },
      options: {},
    });
  },

  /** POST a prepared body ($json.wa_payload) to the WhatsApp Cloud API. */
  whatsappSend(ctx, name, position) {
    const wa = ctx.config.whatsapp;
    return base(ctx, name, 'n8n-nodes-base.httpRequest', 4.2, position, {
      method: 'POST',
      url: 'https://graph.facebook.com/' + wa.graph_api_version + '/' + wa.phone_number_id + '/messages',
      authentication: 'genericCredentialType',
      genericAuthType: 'httpHeaderAuth',
      sendBody: true,
      specifyBody: 'json',
      jsonBody: '={{ JSON.stringify($json.wa_payload) }}',
      options: { timeout: 20000 },
    }, {
      credentials: credential(ctx, 'whatsapp', 'httpHeaderAuth'),
      onError: 'continueRegularOutput', // one bad number must not stop everyone else's reminder
      retryOnFail: true,
      maxTries: 2,
      waitBetweenTries: 3000,
    });
  },

  gmail(ctx, name, position, { to, subject, html }) {
    return base(ctx, name, 'n8n-nodes-base.gmail', 2.1, position, {
      sendTo: to,
      subject,
      emailType: 'html',
      message: html,
      options: { appendAttribution: false },
    }, { credentials: credential(ctx, 'gmail', 'gmailOAuth2'), webhookId: stableId(ctx.config.client.slug, ctx.workflowKey, name, 'webhook') });
  },

  sticky(ctx, name, position, content, { width = 420, height = 260, color = 7 } = {}) {
    return base(ctx, name, 'n8n-nodes-base.stickyNote', 1, position, { content, width, height, color });
  },
};

/** connections helper: link(from, to, fromOutput=0) */
function connector() {
  const connections = {};
  const link = (from, to, out = 0, type = 'main') => {
    connections[from] = connections[from] || {};
    connections[from][type] = connections[from][type] || [];
    while (connections[from][type].length <= out) connections[from][type].push([]);
    connections[from][type][out].push({ node: to, type, index: 0 });
  };
  return { connections, link };
}

function workflow(ctx, name, nodes, connections, extraSettings) {
  return {
    name,
    nodes,
    connections,
    settings: Object.assign({
      executionOrder: 'v1',
      timezone: ctx.config.locale.timezone,
      saveDataErrorExecution: 'all',
      saveDataSuccessExecution: 'all',
      saveManualExecutions: true,
      callerPolicy: 'workflowsFromSameOwner',
    }, extraSettings || {}),
    pinData: {},
    meta: { templateCredsSetupCompleted: false, generatedBy: 'clinic-automation-kit', client: ctx.config.client.slug },
    tags: [],
  };
}

module.exports = { N, connector, workflow, stableId, lib, composeCode, credential };
