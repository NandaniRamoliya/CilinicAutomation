#!/usr/bin/env node
// Build ready-to-import n8n workflows + a setup pack for one client (or all).
//   npm run build -- <client-slug>
//   npm run build -- --all
const fs = require('fs');
const path = require('path');
const { ROOT, loadConfig, runtimeConfig, listClients, DEFAULT_CREDENTIAL_NAMES } = require('./config');
const { APPOINTMENT_COLUMNS } = require('../src/lib/sheet');
const { allSlots, doctorNames, doctorSchedule } = require('../src/lib/schedule');

const DEFINITIONS = [
  require('../src/workflows/05-error-handler'),
  require('../src/workflows/01-book-appointment'),
  ...require('../src/workflows/02-reminders'),
  require('../src/workflows/03-visit-update'),
  require('../src/workflows/04-daily-report'),
  require('../src/workflows/06-razorpay'),
  ...require('../src/workflows/07-ai-receptionist'),
];

/**
 * Build all enabled workflows for a config.
 * ids: optional { [workflowKey]: n8nWorkflowId } — filled by deploy.js so that
 * the error workflow and the AI tool links point at the real workflows.
 */
function buildWorkflows(config, ids) {
  // ids from deploy.js win; otherwise use IDs pasted into config.n8n.workflow_ids (manual-import path)
  const known = Object.assign({}, (config.n8n && config.n8n.workflow_ids) || {}, ids || {});
  return DEFINITIONS.filter((d) => d.enabled(config)).map((def) => {
    const ctx = {
      config,
      runtimeConfig: runtimeConfig(config),
      workflowKey: def.key,
      defaultCredentialNames: DEFAULT_CREDENTIAL_NAMES,
      engineWorkflowId: known.booking_engine || '',
    };
    const json = def.build(ctx);
    if (def.key !== 'error_handler' && known.error_handler) json.settings.errorWorkflow = known.error_handler;
    return { key: def.key, file: def.file, json };
  });
}

function templatesDoc(config) {
  const lib = JSON.parse(fs.readFileSync(path.join(ROOT, 'whatsapp-templates', 'templates.json'), 'utf8'));
  const used = Object.entries(config.whatsapp.templates).filter(([k]) => {
    if (k === 'booking_confirmation') return config.features.booking_confirmation_whatsapp;
    if (k === 'doctor_report') return config.features.doctor_report_whatsapp;
    if (k === 'follow_up_reminder') return config.reminders.follow_up;
    return true;
  });
  const out = ['# WhatsApp templates — ' + config.client.clinic_name, '',
    'Create these in **Meta WhatsApp Manager → Message templates** (category **Utility**), wait for approval,',
    'then keep the names exactly as below. The `{{n}}` order must match `params` in client.config.json.', ''];
  for (const [key, t] of used) {
    const l = lib[key];
    out.push('## ' + t.name + '  (`' + key + '`, language `' + t.language + '`)', '');
    out.push('Parameters in order: ' + t.params.map((p, i) => '{{' + (i + 1) + '}} = `' + p + '`').join(', '), '');
    if (l && JSON.stringify(l.params) === JSON.stringify(t.params)) {
      const body = l.variants[t.language] || l.variants.en;
      out.push('Suggested body:', '', '```', body, '```', '', 'Sample values for Meta review: ' + l.sample.join(' | '), '');
    } else {
      out.push('> Custom parameter order — write your own body using exactly ' + t.params.length + ' variables in the order above.', '');
    }
  }
  if (!used.length) out.push('_WhatsApp is disabled for this client._');
  return out.join('\n');
}

function checklist(config, built) {
  const c = config;
  const has = (k) => built.some((b) => b.key === k);
  const lines = [
    '# Setup checklist — ' + c.client.clinic_name, '',
    'Generated by `npm run build -- ' + c.client.slug + '`. Tick each box during the delivery call.', '',
    '## 1. Accounts (in the CLINIC\'s name)',
    '- [ ] n8n (Cloud or self-hosted) — timezone ' + c.locale.timezone,
    '- [ ] Google account owning the Sheet `' + c.google.sheet_id + '`',
    c.whatsapp.enabled ? '- [ ] Meta Business + WhatsApp Business Platform, phone number id `' + c.whatsapp.phone_number_id + '`' : '- [ ] (WhatsApp disabled)',
    '',
    '## 2. Google Sheet',
    '- [ ] Tab **' + c.google.appointments_tab + '** with header row (exact): `' + APPOINTMENT_COLUMNS.join(',') + '`',
    '- [ ] Columns E, F, L, N, O formatted **Plain text** (Format → Number → Plain text)',
    '- [ ] Tab **Dashboard** with the formulas from `sheet-template/dashboard-formulas.md`',
    '- [ ] Shared only with clinic staff (no public link)',
    '',
    '## 3. n8n credentials (names must match)',
    '- [ ] Google Sheets OAuth2 → `' + (c.n8n.credentials.google_sheets && c.n8n.credentials.google_sheets.name || DEFAULT_CREDENTIAL_NAMES.google_sheets) + '`',
    '- [ ] Gmail OAuth2 → `' + (c.n8n.credentials.gmail && c.n8n.credentials.gmail.name || DEFAULT_CREDENTIAL_NAMES.gmail) + '`',
  ];
  if (c.whatsapp.enabled) lines.push('- [ ] Header Auth → `' + (c.n8n.credentials.whatsapp && c.n8n.credentials.whatsapp.name || DEFAULT_CREDENTIAL_NAMES.whatsapp) + '`: Name `Authorization`, Value `Bearer <permanent system-user token>`');
  if (has('ai_receptionist')) lines.push('- [ ] ' + (c.ai_assistant.provider === 'anthropic' ? 'Anthropic' : 'OpenAI') + ' API credential (AI receptionist)');
  lines.push('', '## 4. Import / deploy',
    '- [ ] Easiest: `N8N_URL=… N8N_API_KEY=… npm run deploy -- ' + c.client.slug + '` (creates/updates all, links error workflow + AI tools)',
    '- [ ] Or import manually in this order:');
  for (const b of built) lines.push('  - `workflows/' + b.file + '` → ' + b.json.name);
  lines.push('- [ ] Open each workflow, fix any node showing a credential warning',
    '- [ ] Every workflow: Settings → Error workflow = "' + c.client.short_name + ' · 0 · Error Handler"', '',
    '## 5. URLs to hand over (after activating)',
    '- Booking form: `<n8n-url>/form/' + c.client.slug + '-book`',
    '- Visit update form: `<n8n-url>/form/' + c.client.slug + '-visit`');
  if (has('razorpay')) lines.push('- Razorpay webhook: `<n8n-url>/webhook/' + c.client.slug + '-razorpay`');
  if (has('ai_receptionist')) lines.push('- WhatsApp AI webhook: `<n8n-url>/webhook/' + c.client.slug + '-whatsapp` (verify token `' + c.ai_assistant.verify_token + '`)');
  lines.push('', '## 6. Configuration summary',
    '- Doctors: ' + doctorNames(c).map((n) => {
      const s = doctorSchedule(c, n);
      return n + ' (' + s.sessions.map((x) => x.start + '-' + x.end).join(', ') + '; closed ' + (s.closed_weekdays.join('/') || 'never') + '; ' + s.patients_per_slot + '/slot)';
    }).join('; '),
    '- Slot length: ' + c.schedule.slot_minutes + ' min → ' + allSlots(c).length + ' slots in the form dropdown',
    '- Reminders: ' + (c.whatsapp.enabled ? c.schedules.reminder_cron + (Number(c.reminders.same_day_hours_before) ? ' + same-day ' + c.reminders.same_day_hours_before + 'h before' : '') : 'off'),
    '- Daily report: ' + c.schedules.report_cron + ' → ' + c.notifications.report_emails.join(', '),
    '- Optional features on: ' + (Object.entries(c.features).filter(([, v]) => v).map(([k]) => k).join(', ') || 'none'),
    '', '## 7. Test before go-live', '- [ ] Run `docs/04-testing-checklist.md` on a COPY of the sheet with your own numbers', '');
  return lines.join('\n');
}

function buildClient(slug, outRoot) {
  const config = loadConfig(slug);
  const built = buildWorkflows(config);
  const out = path.join(outRoot || path.join(ROOT, 'dist'), slug);
  fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(path.join(out, 'workflows'), { recursive: true });
  fs.mkdirSync(path.join(out, 'sheet'), { recursive: true });
  for (const b of built) fs.writeFileSync(path.join(out, 'workflows', b.file), JSON.stringify(b.json, null, 2) + '\n');
  fs.writeFileSync(path.join(out, 'sheet', 'Appointments-header.csv'), APPOINTMENT_COLUMNS.join(',') + '\n');
  fs.copyFileSync(path.join(ROOT, 'sheet-template', 'dashboard-formulas.md'), path.join(out, 'sheet', 'dashboard-formulas.md'));
  fs.writeFileSync(path.join(out, 'whatsapp-templates.md'), templatesDoc(config) + '\n');
  fs.writeFileSync(path.join(out, 'SETUP-CHECKLIST.md'), checklist(config, built));
  fs.writeFileSync(path.join(out, 'manifest.json'), JSON.stringify({
    client: slug,
    workflows: built.map((b) => ({ key: b.key, file: 'workflows/' + b.file, name: b.json.name })),
  }, null, 2) + '\n');
  return { slug, out, count: built.length };
}

if (require.main === module) {
  const args = process.argv.slice(2);
  const slugs = args.includes('--all') ? listClients() : args.filter((a) => !a.startsWith('-'));
  if (!slugs.length) {
    console.error('Usage: npm run build -- city-dental   (your client folder name, no < > brackets)   or   npm run build:all');
    console.error('Clients: ' + listClients().join(', '));
    process.exit(1);
  }
  let failed = false;
  for (const slug of slugs) {
    try {
      const r = buildClient(slug);
      console.log('✔ ' + slug + ': ' + r.count + ' workflows → ' + path.relative(ROOT, r.out));
    } catch (e) {
      failed = true;
      console.error('✖ ' + slug + ': ' + e.message);
    }
  }
  process.exit(failed ? 1 : 0);
}

module.exports = { buildWorkflows, buildClient, DEFINITIONS };
